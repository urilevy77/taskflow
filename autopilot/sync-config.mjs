// sync-config.mjs — the settings that turn on "taps on the phone reach the PC by themselves", and the Pages
// config that deploys them. Shared by marks-sync.mjs (pull / setup) and publish-site.mjs (deploy) so neither
// imports the other.
//
//   AUTOPILOT_MARKS_KV_ID    Cloudflare KV namespace that holds the waiting taps (marks-sync.mjs --setup creates it)
//   AUTOPILOT_ACCESS_TEAM    Cloudflare Access team name (<team>.cloudflareaccess.com)
//   AUTOPILOT_ACCESS_AUD     the Access application's audience tag — the worker checks every request's token against it
//
// All three set → the site is deployed with the worker. Any missing → the site is deployed exactly as before.

/** The sync settings from the environment, or null when any is missing/malformed. */
export function syncConfig(env = process.env) {
  const kvId = String(env.AUTOPILOT_MARKS_KV_ID ?? '').trim();
  const team = String(env.AUTOPILOT_ACCESS_TEAM ?? '').trim();
  const aud = String(env.AUTOPILOT_ACCESS_AUD ?? '').trim();
  return /^[0-9a-f]{32}$/.test(kvId) && /^[a-z0-9][a-z0-9-]{0,62}$/.test(team) && /^[0-9a-f]{64}$/.test(aud) ? { kvId, team, aud } : null;
}

/**
 * Pure: the wrangler.toml for `wrangler pages deploy` — the output directory, the KV binding the worker
 * reads (MARKS) and the two Access values it verifies tokens against. Values are validated by syncConfig(),
 * and the project name by publish-site's validProject(), so nothing here needs escaping.
 */
export function pagesToml({ project, kvId, team, aud, outputDir = '../site' }) {
  return `# Generated by autopilot/publish-site.mjs on every deploy — edit .env, not this file.
name = "${project}"
pages_build_output_dir = "${outputDir}"
compatibility_date = "2026-10-01"

[[kv_namespaces]]
binding = "MARKS"
id = "${kvId}"

[vars]
ACCESS_TEAM = "${team}"
ACCESS_AUD = "${aud}"
`;
}

/** Pages `_routes.json`: only /api/* runs the worker; every page and PDF stays a plain static file. */
export const ROUTES_JSON = JSON.stringify({ version: 1, include: ['/api/*'], exclude: [] });
